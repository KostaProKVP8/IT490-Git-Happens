function doLogin($username,$password)
{
    global $authenticationDB;

    $stmt = $authenticationDB->prepare("SELECT userid, password_hash, is_active FROM users WHERE username = ?;");
    $stmt->bind_param('s', $username);
    $stmt->execute();
    $user = $stmt->get_result()->fetch_assoc();

    var_dump($user);
    // var_dump($password,$user['password_hash']);
    if (!$user || !$user['is_active'] || $password != $user['password_hash']) {
        return array("returnCode" => 0, "message" => "Invalid username or password");
    }

    $sessionKey = generateToken($user['userid']);
    // $sessionKey = generateToken(12345);

    // hashing the session key generated by generateToken
    $sessionHash = hash('sha256', $sessionKey);

    $stmt = $authenticationDB->prepare(
        "INSERT INTO user_sessions (userid, session_key, expires_at)
         VALUES (?, ?, DATE_ADD(NOW(), INTERVAL 1 HOUR))
         ON DUPLICATE KEY UPDATE
            session_key = VALUES(session_key),
            expires_at = VALUES(expires_at)"
    );
    $stmt->bind_param('is', $user['userid'], $sessionHash);
    $stmt->execute();

    return array("returnCode" => 1, "message" => "Login successful", "sessionId" => $sessionKey);

}

